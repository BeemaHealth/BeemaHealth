// Pure helpers for the local CRO dashboard. No network, no server state.
import fs from "node:fs";
import path from "node:path";

export { MIN_VISITORS } from "./metrics.mjs";

const PAGE_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const VARIANT_RE = /^v[a-z0-9]+(?:-[a-z0-9]+)*$/;
export const STATUSES = ["draft", "live", "paused", "archived"];

export const isValidPageKey = (s) => typeof s === "string" && PAGE_RE.test(s);
export const isValidVariantId = (s) =>
  typeof s === "string" && VARIANT_RE.test(s);

const camel = (k) => k.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

/** Reads `id` and `label` out of a variant file's exported descriptor. */
export function parseVariantSource(source) {
  // Scope to the exported descriptor so unrelated `label:` fields are ignored.
  const block = source.slice(source.indexOf("export const variant"));
  const id = block.match(/\bid:\s*"([^"]+)"/)?.[1];
  const label = block.match(/\blabel:\s*"([^"]+)"/)?.[1];
  return id ? { id, label: label ?? id } : null;
}

/** Scans src/landing-variants/<page>/v*.tsx. Returns { [pageKey]: [{id,label,file}] }. */
export function scanVariants(variantsDir) {
  const pages = {};
  for (const entry of fs.readdirSync(variantsDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || !isValidPageKey(entry.name)) continue;
    const dir = path.join(variantsDir, entry.name);
    const list = [];
    for (const f of fs.readdirSync(dir).sort()) {
      const m = f.match(/^(v[a-z0-9-]*)\.tsx$/);
      if (!m || !isValidVariantId(m[1])) continue;
      const meta = parseVariantSource(
        fs.readFileSync(path.join(dir, f), "utf8"),
      );
      if (!meta || meta.id !== m[1]) continue;
      list.push({ id: meta.id, label: meta.label, file: f });
    }
    if (list.length) pages[entry.name] = list;
  }
  return pages;
}

/**
 * experiments.json is the source of truth:
 * { [page]: { experimentId, variants: { [variantId]: { status, weight } } } }
 * Variant files missing from it are drafts with no traffic.
 */
export function normalizeConfig(raw, pages) {
  const out = {};
  for (const [page, variants] of Object.entries(pages)) {
    const r = raw?.[page] ?? {};
    out[page] = {
      experimentId: r.experimentId ?? `${page}-e1`,
      variants: Object.fromEntries(
        variants.map((v) => {
          const c = r.variants?.[v.id];
          return [
            v.id,
            { status: c?.status ?? "draft", weight: c?.weight ?? 0 },
          ];
        }),
      ),
    };
  }
  return out;
}

/** Returns a list of problems (empty = valid) for one page's config. */
export function validatePageConfig(cfg) {
  const problems = [];
  let liveTotal = 0;
  let liveCount = 0;
  for (const [id, v] of Object.entries(cfg.variants)) {
    if (!isValidVariantId(id)) problems.push(`Bad variant id ${id}`);
    if (!STATUSES.includes(v.status))
      problems.push(`${id}: unknown status ${v.status}`);
    if (!Number.isInteger(v.weight) || v.weight < 0 || v.weight > 100)
      problems.push(`${id}: weight must be a whole number 0-100`);
    if (v.status === "live") {
      liveCount += 1;
      liveTotal += v.weight;
      if (v.weight === 0)
        problems.push(`${id}: live variants need weight above 0`);
    } else if (v.weight !== 0) {
      problems.push(`${id}: only live variants can have traffic`);
    }
  }
  if (liveCount === 0) problems.push("At least one variant must be live");
  else if (liveTotal !== 100)
    problems.push(`Live weights total ${liveTotal}, must be 100`);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(cfg.experimentId))
    problems.push("Bad experiment id");
  return problems;
}

/** Builds src/landing-variants/experiments.generated.ts. Only live variants are imported. */
export function renderGenerated(config) {
  const imports = [];
  const blocks = [];
  for (const page of Object.keys(config).sort()) {
    const problems = validatePageConfig(config[page]);
    if (problems.length) throw new Error(`${page}: ${problems.join("; ")}`);
    const live = Object.entries(config[page].variants)
      .filter(([, v]) => v.status === "live")
      .sort((a, b) => b[1].weight - a[1].weight || a[0].localeCompare(b[0]));
    const rows = live.map(([id, v], i) => {
      const name = `${camel(page)}V${i}`;
      imports.push(`import { variant as ${name} } from "./${page}/${id}";`);
      return `      { variant: ${name}, weight: ${v.weight} },`;
    });
    blocks.push(
      `  "${page}": {\n    experimentId: "${config[page].experimentId}",\n    variants: [\n${rows.join("\n")}\n    ],\n  },`,
    );
  }
  return `// GENERATED by the local CRO dashboard (tools/cro). Do not edit by hand.
// Edit traffic in the dashboard; it rewrites experiments.json and this file.
// Only live variants are imported, so drafts and paused variants never ship.
import type { ExperimentConfig } from "./types";
${imports.join("\n")}

export const EXPERIMENTS = {
${blocks.join("\n")}
} as const satisfies Record<string, ExperimentConfig>;
`;
}

/** "tirzepatide-houston-e3" -> "tirzepatide-houston-e4". */
export function nextExperimentId(current) {
  const m = /^(.*)-e(\d+)$/.exec(current);
  return m ? `${m[1]}-e${Number(m[2]) + 1}` : `${current}-e2`;
}

/** Next free variant id like "v2-short-hero" for a page. */
export function nextVariantId(existingIds, name) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name))
    throw new Error("Name must be lowercase letters, numbers, and hyphens");
  const max = Math.max(
    0,
    ...existingIds.map((id) => Number(/^v(\d+)/.exec(id)?.[1] ?? 0)),
  );
  return `v${max + 1}-${name}`;
}

/** Copies a variant's source under a new id and label. */
export function cloneVariantSource(source, id, label) {
  const at = source.indexOf("export const variant");
  if (at < 0) throw new Error("Source has no variant descriptor");
  return (
    source.slice(0, at) +
    source
      .slice(at)
      .replace(/\bid:\s*"[^"]+"/, `id: "${id}"`)
      .replace(/\blabel:\s*"[^"]+"/, `label: ${JSON.stringify(label)}`)
  );
}

// ---- Deploy log: deploys.json = [{ page, at, config: { [variantId]: {status, weight} } }]
// Toggling locally changes nothing for visitors. A variant is only "live on the
// site" once the user confirms a deploy, which snapshots the config at that time.

export function lastDeploy(deploys, page) {
  return (
    deploys
      .filter((d) => d.page === page)
      .sort((a, b) => a.at.localeCompare(b.at))
      .at(-1) ?? null
  );
}

export function recordDeploy(deploys, page, pageConfig, at) {
  return [
    ...deploys,
    {
      page,
      at,
      experimentId: pageConfig.experimentId,
      config: pageConfig.variants,
    },
  ];
}

/** True when the local config differs from what the last confirmed deploy shipped. */
export function undeployedChanges(deploys, page, pageConfig) {
  const last = lastDeploy(deploys, page);
  if (!last) return true;
  if (last.experimentId !== pageConfig.experimentId) return true;
  const ids = new Set([
    ...Object.keys(last.config),
    ...Object.keys(pageConfig.variants),
  ]);
  for (const id of ids) {
    const a = last.config[id] ?? { status: "draft", weight: 0 };
    const b = pageConfig.variants[id] ?? { status: "draft", weight: 0 };
    if (a.status !== b.status || a.weight !== b.weight) return true;
  }
  return false;
}

/** Latest confirmed-deploy time at which this variant became live (and stayed live). */
export function lastActivation(deploys, page, variantId) {
  const list = deploys
    .filter((d) => d.page === page)
    .sort((a, b) => a.at.localeCompare(b.at));
  let since = null;
  for (const d of list) {
    const live = d.config[variantId]?.status === "live";
    if (live && !since) since = d.at;
    if (!live) since = null;
  }
  return since;
}
