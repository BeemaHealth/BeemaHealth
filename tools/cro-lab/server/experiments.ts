// Reads and writes src/landing-variants/experiments.json and the generated
// experiments.generated.ts. The CRO Lab runs sequential tests, so every page
// has exactly one live variant at 100% traffic.
import fs from "node:fs";
import path from "node:path";
import { scanDisk } from "./variants.ts";

type Entry = { status: "live" | "draft"; weight: number };
export type ExperimentsFile = Record<
  string,
  { experimentId: string; variants: Record<string, Entry> }
>;

const dir = (root: string) => path.join(root, "src/landing-variants");
const jsonPath = (root: string) => path.join(dir(root), "experiments.json");
const generatedPath = (root: string) =>
  path.join(dir(root), "experiments.generated.ts");

const camel = (s: string) =>
  s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

export function readExperiments(root: string): ExperimentsFile {
  try {
    return JSON.parse(fs.readFileSync(jsonPath(root), "utf8"));
  } catch {
    return {};
  }
}

/** The variant id the local code serves for a page (the single live entry). */
export function mainVariantId(
  file: ExperimentsFile,
  pageId: string,
): string | null {
  const live = Object.entries(file[pageId]?.variants ?? {}).filter(
    ([, v]) => v.status === "live",
  );
  return live.length === 1 ? live[0][0] : null;
}

/**
 * Returns a copy of `file` where `variantId` is the only live variant of
 * `pageId` and every variant file on disk is listed. Throws if the variant has
 * no file. Other pages are left untouched.
 */
export function withMain(
  file: ExperimentsFile,
  root: string,
  pageId: string,
  variantId: string,
): ExperimentsFile {
  const onDisk = scanDisk(root, pageId).map((f) => f.id);
  if (!onDisk.includes(variantId))
    throw new Error(`No variant file for ${pageId}/${variantId}`);
  const prev = file[pageId];
  const next: ExperimentsFile = { ...file };
  next[pageId] = {
    experimentId: prev?.experimentId ?? `${pageId}-e1`,
    variants: Object.fromEntries(
      onDisk.map((id) => [
        id,
        id === variantId
          ? { status: "live", weight: 100 }
          : { status: "draft", weight: 0 },
      ]),
    ),
  };
  return next;
}

/** Source of experiments.generated.ts. Only live variants are imported. */
export function renderGenerated(file: ExperimentsFile): string {
  const imports: string[] = [];
  const blocks: string[] = [];
  for (const pageId of Object.keys(file).sort()) {
    const id = mainVariantId(file, pageId);
    if (!id) throw new Error(`${pageId} must have exactly one live variant`);
    const name = `${camel(pageId)}V0`;
    imports.push(`import { variant as ${name} } from "./${pageId}/${id}";`);
    blocks.push(
      `  "${pageId}": {\n    experimentId: "${file[pageId].experimentId}",\n    variants: [{ variant: ${name}, weight: 100 }],\n  },`,
    );
  }
  return `// GENERATED by the local CRO dashboard (tools/cro-lab). Do not edit by hand.
// Use "Make main" in the dashboard; it rewrites experiments.json and this file.
// Only live variants are imported, so drafts and paused variants never ship.
import type { ExperimentConfig } from "./types";
${imports.join("\n")}

export const EXPERIMENTS = {
${blocks.join("\n")}
} as const satisfies Record<string, ExperimentConfig>;
`;
}

/** Writes both files. Validates (renders) before touching disk. */
export async function writeExperiments(
  root: string,
  file: ExperimentsFile,
): Promise<void> {
  const generated = renderGenerated(file);
  const prettier = await import("prettier");
  const options = (await prettier.resolveConfig(generatedPath(root))) ?? {};
  const formatted = await prettier.format(generated, {
    ...options,
    filepath: generatedPath(root),
  });
  fs.writeFileSync(jsonPath(root), JSON.stringify(file, null, 2) + "\n");
  fs.writeFileSync(generatedPath(root), formatted);
}
